namespace Grove.Components.Primitives;

/// <summary>
/// Specifies the ways a <see cref="Grove.Components.Primitives.GroveTimeline" /> component renders line and content items.
/// </summary>
public enum LinePosition
{
    /// <summary>
    /// The GroveTimeline line is displayed at the center of the component.
    /// </summary>
    Center,

    /// <summary>
    /// The GroveTimeline line is displayed at the center of the component with alternating content position.
    /// </summary>
    Alternate,

    /// <summary>
    /// The GroveTimeline line is displayed at the start of the component.
    /// </summary>
    Start,

    /// <summary>
    /// The GroveTimeline line is displayed at the end of the component.
    /// </summary>
    End,

    /// <summary>
    /// The GroveTimeline line is displayed at the left side of the component.
    /// </summary>
    Left,

    /// <summary>
    /// The GroveTimeline line is displayed at the right side of the component.
    /// </summary>
    Right,

    /// <summary>
    /// The GroveTimeline line is displayed at the top of the component.
    /// </summary>
    Top,

    /// <summary>
    /// The GroveTimeline line is displayed at the bottom of the component.
    /// </summary>
    Bottom
}

