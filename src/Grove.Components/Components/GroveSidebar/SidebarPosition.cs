namespace Grove.Components.Primitives;

/// <summary>
/// Specifies the ways a <see cref="Grove.Components.Primitives.GroveSidebar" /> component renders inside GroveLayout.
/// </summary>
public enum SidebarPosition
{
    /// <summary>
    /// The GroveSidebar component is displayed at the start of GroveLayout.
    /// </summary>
    Left,

    /// <summary>
    /// The GroveSidebar component is displayed at the end of GroveLayout.
    /// </summary>
    Right,

    /// <summary>
    /// The GroveSidebar component is displayed at the start of GroveLayout.
    /// </summary>
    Start,

    /// <summary>
    /// The GroveSidebar component is displayed at the end of GroveLayout.
    /// </summary>
    End
}

