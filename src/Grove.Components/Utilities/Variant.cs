namespace Grove.Components.Primitives;

/// <summary>
/// Specifies the design variant of <see cref="Grove.Components.Primitives.GroveButton" /> and <see cref="Grove.Components.Primitives.GroveBadge" />. Affects the visual styling of GroveButton and GroveBadge.
/// </summary>
public enum Variant
{
    /// <summary>
    /// A filled appearance.
    /// </summary>
    Filled,

    /// <summary>
    /// A flat appearance without any drop shadows.
    /// </summary>
    Flat,

    /// <summary>
    /// A text appearance.
    /// </summary>
    Text,

    /// <summary>
    /// An outlined appearance.
    /// </summary>
    Outlined
}

